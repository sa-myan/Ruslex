#!/usr/bin/env python3
"""Manage ONLY Ruslex's own Caddy site; never restart the shared proxy.

Supports both /srv/proxy/{Caddyfile,sites} and the older /srv/proxy/config
layout. Pre-existing inline sites are never duplicated or removed.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path("/srv/proxy")
MARKER = "# Managed by Ruslex; do not edit this file manually\n"


def layout() -> tuple[Path, Path]:
    """Prefer the existing shared proxy layout; never create directories."""
    for base in (ROOT, ROOT / "config"):
        main, sites = base / "Caddyfile", base / "sites"
        if main.is_file() and sites.is_dir():
            return main, sites / "ruslex.caddy"
    raise RuntimeError("Shared Caddy layout not found; see docs/VPS_FOUNDATIONS.md")


def docker_caddy(action: str):
    subprocess.run(["docker", "exec", "proxy-caddy-1", "caddy", action,
                    "--config", "/etc/caddy/Caddyfile"], check=True)


def hostname_from_env() -> str:
    env = Path(__file__).resolve().parents[1] / ".env"
    if not env.is_file():
        raise RuntimeError("Run ./manage.sh init before publishing")
    origins = [line.partition("=")[2].strip() for line in env.read_text().splitlines()
               if line.startswith("PUBLIC_ORIGIN=")]
    if len(origins) != 1 or not origins[0].startswith("https://"):
        raise RuntimeError("PUBLIC_ORIGIN must be a single https://hostname")
    return origins[0].removeprefix("https://").split("/", 1)[0]


def configure(action: str, *, dry_run: bool = False) -> str:
    main, site_file = layout()
    if "import /etc/caddy/sites/*.caddy" not in main.read_text():
        raise RuntimeError("Main Caddyfile does not import /etc/caddy/sites/*.caddy")
    original = site_file.read_text() if site_file.is_file() else None
    if original is not None and not original.startswith((MARKER, "# Managed by the standalone Ruslex installer")):
        raise RuntimeError("Refusing to change an unmanaged Caddy site")
    host = hostname_from_env()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.-]*[A-Za-z0-9]", host):
        raise ValueError("Invalid public hostname")

    # The existing VPS already has an inline, standalone Ruslex site.
    # Never create a duplicate host declaration or remove it accidentally.
    main_text = main.read_text()
    inline = re.search(
        r"(?m)^" + re.escape(host) + r"\s*\{(?P<body>[^{}]*)\}",
        main_text,
    )
    if inline:
        if action == "unpublish":
            raise RuntimeError(
                f"Ruslex route is inline in {main}; refusing to unpublish it automatically"
            )
        if "reverse_proxy ruslex-web:8000" not in inline.group("body"):
            raise RuntimeError(
                f"Ruslex hostname already declared with a different upstream in {main}"
            )
        return f"Ruslex already published inline in {main}; no changes needed"

    for other in site_file.parent.glob("*.caddy"):
        if other != site_file and re.search(
            r"(?<![\\w.-])" + re.escape(host) + r"(?![\\w.-])",
            other.read_text(),
        ):
            raise ValueError(f"Hostname is already declared by {other}")

    expected = MARKER + f"{host} {{\n    encode zstd gzip\n    reverse_proxy ruslex-web:8000\n}}\n"
    if action == "publish":
        new = expected
    elif action == "unpublish":
        new = None
    else:
        raise ValueError("Unknown Caddy action")
    if dry_run:
        return expected if new is not None else f"Would remove {site_file}"
    if new == original:
        return "Caddy site already matches; no reload needed"
    try:
        if new is None:
            site_file.unlink(missing_ok=True)
        else:
            site_file.write_text(new)
        docker_caddy("validate")
        docker_caddy("reload")
    except Exception:
        if original is None:
            site_file.unlink(missing_ok=True)
        else:
            site_file.write_text(original)
        try:
            docker_caddy("reload")
        except Exception:
            pass
        raise
    return f"Caddy site {'published' if new else 'unpublished'}: {site_file}"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("publish", "unpublish"))
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    print(configure(args.action, dry_run=args.dry_run))


if __name__ == "__main__":
    main()
