<script lang="ts">
  import type { WordForm } from '../../lib/types';
  import { organizeWordForms } from '../../lib/wordForms';

  interface Props {
    forms: WordForm[];
    pos: string;
  }
  let { forms, pos }: Props = $props();
  let showOther = $state(false);
  let showAnalyses = $state(false);
  const organized = $derived(organizeWordForms(forms, pos));
</script>

{#if organized.unique.length}
  <section class="surface p-4 sm:p-5 mt-5">
    <div class="flex flex-wrap items-start justify-between gap-3">
      <div>
        <h3 class="text-xl font-semibold">Word forms</h3>
        <p class="text-xs opacity-65 mt-1">
          Generated by pymorphy3. These forms are not necessarily attested in the textbook;
          their stress has not been verified.
        </p>
      </div>
      <span class="badge badge-outline">{organized.spellingCount} forms</span>
    </div>

    {#each organized.tables as table (table.title)}
      <div class="mt-5">
        <h4 class="font-semibold mb-2">{table.title}</h4>
        <div class="overflow-x-auto rounded-lg border border-base-300">
          <table class="table table-sm w-full">
            <thead>
              <tr>
                <th scope="col" class="min-w-28">{table.title === 'Declension' || table.title === 'Full forms' ? 'Case' : 'Form'}</th>
                {#each table.columns as column}
                  <th scope="col" class="min-w-24">{column}</th>
                {/each}
              </tr>
            </thead>
            <tbody>
              {#each table.rows as row (row.label)}
                <tr>
                  <th scope="row" class="font-medium text-sm whitespace-nowrap">{row.label}</th>
                  {#each row.cells as variants, index (index)}
                    <td>
                      {#if variants.length}
                        <span class="russian font-medium">{variants.join(' / ')}</span>
                      {:else}
                        <span class="opacity-30" aria-label="Not applicable">—</span>
                      {/if}
                    </td>
                  {/each}
                </tr>
              {/each}
            </tbody>
          </table>
        </div>
      </div>
    {/each}

    {#if organized.other.length}
      <div class="mt-4">
        <button
          type="button"
          class="btn btn-sm btn-outline"
          aria-expanded={showOther}
          onclick={() => { showOther = !showOther; }}
        >
          {showOther ? 'Hide' : 'Show'} {organized.other.length} other analyses
        </button>
        {#if showOther}
          <div class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2 mt-3">
            {#each organized.other as item (item.form + '/' + item.grammemes)}
              <div class="rounded-lg border border-base-300 p-2">
                <div class="russian font-medium">{item.form}</div>
                <div class="text-xs opacity-60 break-words mt-1" title={item.grammemes}>
                  {item.grammemes.replaceAll(',', ' · ')}
                </div>
              </div>
            {/each}
          </div>
        {/if}
      </div>
    {/if}

    <div class="mt-4">
      <button
        type="button"
        class="btn btn-ghost btn-sm"
        aria-expanded={showAnalyses}
        onclick={() => { showAnalyses = !showAnalyses; }}
      >
        {showAnalyses ? 'Hide' : 'Show'} all {organized.unique.length} grammatical analyses
      </button>
      {#if showAnalyses}
        <div class="overflow-x-auto mt-2 rounded-lg border border-base-300">
          <table class="table table-xs w-full">
            <thead>
              <tr><th scope="col">Form</th><th scope="col">Morphological tags</th></tr>
            </thead>
            <tbody>
              {#each organized.unique as item (item.form + '/' + item.grammemes)}
                <tr>
                  <td class="russian font-medium">{item.form}</td>
                  <td class="text-xs opacity-75 break-words">{item.grammemes.replaceAll(',', ' · ')}</td>
                </tr>
              {/each}
            </tbody>
          </table>
        </div>
      {/if}
    </div>
  </section>
{/if}
