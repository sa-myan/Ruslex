<script lang="ts">
  import type { WordForm } from '../../lib/types';
  import { organizeWordForms } from '../../lib/wordForms';

  interface Props {
    forms: WordForm[];
    pos: string;
  }
  let { forms, pos }: Props = $props();
  let showOther = $state(false);
  let showAnalyses = $state(false);
  const organized = $derived(organizeWordForms(forms, pos));
</script>
{#if organized.unique.length}
  <section class="surface p-4 sm:p-5 mt-5">
    <div class="flex flex-wrap justify-between items-start gap-3">
      <div>
        <h3 class="text-xl font-semibold">Word forms</h3>
        <p class="text-xs opacity-65 mt-1">
          Generated by pymorphy3, not necessarily attested in the textbook.
          Stress on inflected forms is not verified.
        </p>
      </div>
      <span class="badge badge-outline">{organized.spellingCount} spellings</span>
    </div>
    {#each organized.tables as table (table.title)}
      <div class="mt-5">
        <h4 class="font-semibold text-sm mb-2">{table.title}</h4>
        <div class="overflow-x-auto rounded-lg border border-base-300">
          <table class="table table-sm w-full">
            <thead>
              <tr>
                <th scope="col">Grammar</th>
                {#each table.columns as column (column)}
                  <th scope="col">{column}</th>
                {/each}
              </tr>
            </thead>
            <tbody>
              {#each table.rows as row (row.label)}
                <tr>
                  <th scope="row" class="font-medium whitespace-nowrap">{row.label}</th>
                  {#each row.cells as values, index (index)}
                    <td>
                      {#if values.length}
                        <div class="flex flex-wrap gap-x-2 gap-y-1">
                          {#each values as value (value)}
                            <span class="russian text-base">{value}</span>
                          {/each}
                        </div>
                      {:else}
                        <span class="opacity-40" aria-label="No form">—</span>
                      {/if}
                    </td>
                  {/each}
                </tr>
              {/each}
            </tbody>
          </table>
        </div>
      </div>
    {/each}
    {#if organized.other.length}
      <div class="mt-5">
        <button
          type="button"
          class="btn btn-sm btn-outline"
          aria-expanded={showOther}
          onclick={() => { showOther = !showOther; }}
        >
          {showOther ? 'Hide' : 'Show'} {organized.other.length} other forms
        </button>
        {#if showOther}
          <p class="text-xs opacity-65 mt-2">
            These forms have analyses not included in the common tables above.
          </p>
          <div class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-2 mt-3">
            {#each organized.other as item (item.form + '/' + item.grammemes)}
              <div class="border border-base-300 rounded-lg p-2">
                <div class="russian font-medium">{item.form}</div>
                <div class="text-xs opacity-60 mt-1 break-words">{item.grammemes.replaceAll(',', ' · ')}</div>
              </div>
            {/each}
          </div>
        {/if}
      </div>
    {/if}
    <button
      class="btn btn-sm btn-outline mt-5"
      aria-expanded={showAnalyses}
      onclick={() => { showAnalyses = !showAnalyses; }}
    >
      {showAnalyses ? 'Hide grammatical analyses' : `Show all ${organized.unique.length} grammatical analyses`}
    </button>
    {#if showAnalyses}
      <div class="mt-3 overflow-x-auto rounded-lg border border-base-300">
        <table class="table table-xs w-full">
          <thead><tr><th scope="col">Form</th><th scope="col">Grammemes</th></tr></thead>
          <tbody>
            {#each organized.unique as item (item.form + '/' + item.grammemes)}
              <tr>
                <td class="russian text-sm">{item.form}</td>
                <td class="text-xs break-words">{item.grammemes.replaceAll(',', ' · ')}</td>
              </tr>
            {/each}
          </tbody>
        </table>
      </div>
    {/if}
  </section>
{/if}
